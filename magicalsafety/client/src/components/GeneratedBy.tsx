import { MockBadge } from "./MockBadge";

/** Always says who wrote the interpretation, so a reader can tell AI from rules. */
export function GeneratedBy({ by }: { by: string }) {
  return by === "rules" ? (
    <span className="inline-flex items-center gap-2 text-xs text-slate-300"><MockBadge label="RULES" /> Generated by rules (no AI)</span>
  ) : (
    <span className="inline-flex items-center gap-2 text-xs text-sky-200"><span className="rounded bg-sky-900 px-1.5 py-0.5 font-semibold">AI</span> Generated by {by}</span>
  );
}
